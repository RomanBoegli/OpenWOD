// Bundles the workout registry (workouts/<collection>/<id>.wod.yaml, hand-written) into
// packages/domain/src/generated/bundled.ts, which the app, the tests and the server import.
//   npm run workouts:bundle          # regenerate after editing a file
//   npm run workouts:check           # fail when the generated module is out of date (part of npm run check)
// Every file must parse as a current workout file, carry the id its name says, and name only movements the
// catalogue knows (the voice packs render one clip per catalogue record, so unknown names would fall back to the
// device voice). A folder with a collection.yaml is a bundled collection; folders without one only group files.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import YAML from 'yaml';
import { Catalogue } from '../packages/domain/src/catalogue';
import { parseWorkoutFile, WorkoutValidationError, type Workout } from '../packages/domain/src';
import { collectPrescriptions } from '../packages/domain/src/library';
import { seedMovements } from '../packages/domain/src/movements';

const ROOT = 'workouts';
const OUT = 'packages/domain/src/generated/bundled.ts';
const check = process.argv.includes('--check');
const catalogue = new Catalogue(seedMovements);
const problems: string[] = [];

interface BundledCollection { id: string; title: string; description: string; workoutIds: string[] }
const collections: BundledCollection[] = [];
const workouts: Workout[] = [];
const seen = new Map<string, string>();

for (const folder of (await readdir(ROOT, { withFileTypes: true })).filter(entry => entry.isDirectory()).map(entry => entry.name).sort()) {
  const files = (await readdir(join(ROOT, folder))).sort();
  const ids: string[] = [];
  for (const file of files.filter(name => name.endsWith('.wod.yaml'))) {
    const path = join(ROOT, folder, file);
    let workout: Workout;
    try { workout = parseWorkoutFile(await readFile(path, 'utf8')); } catch (error) {
      problems.push(`${path}: ${error instanceof WorkoutValidationError ? error.message.replace(/\n/g, '; ') : String(error)}`);
      continue;
    }
    if (`${workout.id}.wod.yaml` !== file) problems.push(`${path}: the file is named after id "${file.replace(/\.wod\.yaml$/, '')}" but the workout id is "${workout.id}".`);
    if (seen.has(workout.id)) problems.push(`${path}: id "${workout.id}" is already used by ${seen.get(workout.id)}.`);
    seen.set(workout.id, path);
    const unknown = [...new Set(collectPrescriptions(workout).filter(item => !catalogue.resolve(item)).map(item => item.name))];
    if (unknown.length) problems.push(`${path}: movements not in the catalogue (packages/domain/src/movements.ts): ${unknown.join(', ')}.`);
    // A bundled workout carries a deterministic sharing identity so an export from any installation is recognised on reimport (SHR-05).
    workouts.push({ ...workout, sharing: { id: `openwod.bundled:${workout.id}`, sourceRevision: workout.revision } });
    ids.push(workout.id);
  }
  if (files.includes('collection.yaml')) {
    const meta = YAML.parse(await readFile(join(ROOT, folder, 'collection.yaml'), 'utf8')) as { title?: unknown; description?: unknown };
    if (typeof meta?.title !== 'string' || !meta.title.trim()) problems.push(`${join(ROOT, folder, 'collection.yaml')}: needs a title.`);
    collections.push({ id: folder, title: String(meta.title ?? folder).trim(), description: typeof meta.description === 'string' ? meta.description.trim() : '', workoutIds: ids });
  }
}

if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const content = [
  `// Generated by scripts/bundle-workouts.ts from ${ROOT}/**. Do not edit; edit the YAML files and run npm run workouts:bundle.`,
  `import type { Workout } from '../schema';`,
  ``,
  `export interface BundledCollection { id: string; title: string; description: string; workoutIds: string[] }`,
  `export const bundledCollections: BundledCollection[] = ${JSON.stringify(collections, null, 2)};`,
  ``,
  `export const bundledWorkouts: Workout[] = [`,
  ...workouts.map(workout => `  ${JSON.stringify(workout)},`),
  `];`,
  ``,
].join('\n');

if (check) {
  if (await readFile(OUT, 'utf8').catch(() => '') !== content) { console.error(`${OUT} is out of date. Run npm run workouts:bundle.`); process.exit(1); }
  console.log(`${workouts.length} bundled workouts in ${collections.length} collections are up to date.`);
} else {
  await writeFile(OUT, content);
  console.log(`Bundled ${workouts.length} workouts in ${collections.length} collections into ${OUT}.`);
}
