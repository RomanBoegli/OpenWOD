// Renders the fixed spoken cues with open-licensed Piper voices into apps/web/public/cues/<pack>/*.mp3 plus packs.json.
// Runs in the Docker image build (PIPER_RUNNER=piper: the installed `piper` CLI) and locally (default: uv, which fetches piper-tts on demand).
// Piper 1.8 no longer downloads voices itself, so each voice is fetched once with `python -m piper.download_voices` first.
//   npm run cues:generate                       # every pack
//   CUE_PACKS=british npm run cues:generate     # one pack
//   CUES_OUT=dist/web/cues npm run cues:generate
// Requires ffmpeg. Piper ships English voices in British and American variants only (no Australian, no impersonations).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const CUES = {
  'get-ready': 'Get ready.',
  go: 'Go!',
  rest: 'Rest.',
  switch: 'Switch!',
  three: 'Three.',
  two: 'Two.',
  one: 'One.',
  paused: 'Paused.',
  resume: 'Resume.',
  complete: 'Workout complete. Well done.',
};
/** Packs ship in this order; the first one is the default in the app. */
export const PACKS = [
  { id: 'british', label: 'British male (Alan)', voice: 'en_GB-alan-medium' },
  { id: 'american', label: 'American female (Amy)', voice: 'en_US-amy-medium' },
  { id: 'scottish', label: 'Scottish female (Alba)', voice: 'en_GB-alba-medium' },
];

const outDir = resolve(process.env.CUES_OUT ?? 'apps/web/public/cues');
const wanted = (process.env.CUE_PACKS ?? '').split(',').map(item => item.trim()).filter(Boolean);
const packs = wanted.length ? PACKS.filter(pack => wanted.includes(pack.id)) : PACKS;
const runner = process.env.PIPER_RUNNER ?? 'uvx';
const work = mkdtempSync(join(tmpdir(), 'openwod-cues-'));
mkdirSync(outDir, { recursive: true });

function run(command, args, input) {
  const result = spawnSync(command, args, { input, stdio: ['pipe', 'inherit', 'inherit'] });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed with status ${result.status}`);
}
const voicesDir = join(work, 'voices');
function downloadVoice(voice) {
  const args = ['-m', 'piper.download_voices', voice, '--download-dir', voicesDir];
  if (runner === 'uvx') run('uv', ['run', '--with', 'piper-tts', 'python', ...args]);
  else run('python3', args);
}
function piper(voice, wav, text) {
  const args = ['--model', voice, '--data-dir', voicesDir, '--output_file', wav];
  if (runner === 'uvx') run('uvx', ['--from', 'piper-tts', 'piper', ...args], text);
  else run(runner, args, text);
}

const rendered = [];
for (const pack of packs) {
  const packDir = join(outDir, pack.id);
  mkdirSync(packDir, { recursive: true });
  downloadVoice(pack.voice);
  for (const [name, text] of Object.entries(CUES)) {
    const wav = join(work, `${pack.id}-${name}.wav`);
    piper(pack.voice, wav, text);
    // Trim silence, normalise loudness, encode mono MP3 (decodable by every supported browser).
    run('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5', '-ac', '1', '-ar', '32000', '-b:a', '48k', join(packDir, `${name}.mp3`)]);
  }
  rendered.push(pack);
}
// Keep packs that already exist in the output (an earlier partial render) listed, in canonical order.
const listed = PACKS.filter(pack => rendered.includes(pack) || existsSync(join(outDir, pack.id, 'go.mp3')));
writeFileSync(join(outDir, 'packs.json'), JSON.stringify(listed.map(({ id, label, voice }) => ({ id, label, voice })), null, 2) + '\n');
writeFileSync(join(outDir, 'LICENSE.md'), `# Spoken cue clips\n\nGenerated by scripts/generate-cues.mjs with Piper text-to-speech voices (https://github.com/rhasspy/piper): ${listed.map(pack => `\`${pack.voice}\``).join(', ')}. Piper voice models carry their own licences, recorded in each voice's MODEL_CARD on Hugging Face (rhasspy/piper-voices); the voices used here allow redistribution of generated audio. The clips follow this repository's licence.\n`);
rmSync(work, { recursive: true, force: true });
console.log(`Rendered ${rendered.length} pack(s) × ${Object.keys(CUES).length} cues into ${outDir}: ${listed.map(pack => pack.id).join(', ')}`);
