// Renders the fixed spoken cues once, with an open-licensed Piper voice, into apps/web/public/cues/*.mp3.
// One-off developer step; the clips are committed. Requires `uv` (runs piper-tts on demand) and `ffmpeg`.
//   npm run cues:generate              # default voice en_GB-alan-medium
//   PIPER_VOICE=en_US-lessac-medium npm run cues:generate
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const CUES = {
  'get-ready': 'Get ready.',
  go: 'Go!',
  rest: 'Rest.',
  switch: 'Switch!',
  three: 'Three.',
  two: 'Two.',
  one: 'One.',
  paused: 'Paused.',
  resume: 'Resume.',
  complete: 'Workout complete. Well done.',
};
const voice = process.env.PIPER_VOICE ?? 'en_GB-alan-medium';
const outDir = resolve('apps/web/public/cues');
const work = mkdtempSync(join(tmpdir(), 'wodva-cues-'));
mkdirSync(outDir, { recursive: true });

function run(command, args, input) {
  const result = spawnSync(command, args, { input, stdio: ['pipe', 'inherit', 'inherit'] });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed with status ${result.status}`);
}

for (const [name, text] of Object.entries(CUES)) {
  const wav = join(work, `${name}.wav`);
  run('uvx', ['--from', 'piper-tts', 'piper', '--model', voice, '--download-dir', join(work, 'voices'), '--data-dir', join(work, 'voices'), '--output_file', wav], text);
  // Trim silence, normalise loudness, encode mono MP3 (decodable by every supported browser).
  run('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5', '-ac', '1', '-ar', '32000', '-b:a', '48k', join(outDir, `${name}.mp3`)]);
}
writeFileSync(join(outDir, 'LICENSE.md'), `# Spoken cue clips\n\nGenerated by scripts/generate-cues.mjs with the Piper text-to-speech voice \`${voice}\` (https://github.com/rhasspy/piper). Piper voice models carry their own licences, recorded in the voice's MODEL_CARD on Hugging Face (rhasspy/piper-voices); \`en_GB-alan-medium\` and \`en_US-lessac-medium\` are distributed under permissive terms that allow redistribution of generated audio. The clips themselves are part of this repository and follow its licence.\n`);
rmSync(work, { recursive: true, force: true });
console.log(`Rendered ${Object.keys(CUES).length} cues with ${voice} into ${outDir}`);
