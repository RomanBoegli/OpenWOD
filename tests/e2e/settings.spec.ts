    await page.getByRole('searchbox', { name: 'Search workouts' }).fill('fran');
    await expect(list.getByRole('heading', { level: 2 }).first()).toHaveText('Fran');
    await page.getByRole('searchbox', { name: 'Search workouts' }).fill('');
